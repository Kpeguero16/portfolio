// Writes data/prs.js: every PR Khalil merged into Swarms and the Swarms docs.
// Run: GITHUB_TOKEN=$(gh auth token) node scripts/fetch-prs.mjs
// The daily workflow in .github/workflows/refresh-prs.yml runs it too.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
if (!token) { console.error('Set GITHUB_TOKEN (or GH_TOKEN).'); process.exit(1); }

const AUTHOR = 'Kpeguero16';
const REPOS = { 'kyegomez/swarms': 'code', 'The-Swarm-Corporation/swarms-framework-docs': 'docs' };
const q = `author:${AUTHOR} is:pr is:merged ${Object.keys(REPOS).map(r => `repo:${r}`).join(' ')}`;
const query = `query($q: String!, $after: String) {
  search(query: $q, type: ISSUE, first: 100, after: $after) {
    pageInfo { hasNextPage endCursor }
    nodes { ... on PullRequest { number title additions deletions mergedAt url repository { nameWithOwner } } }
  }
}`;

const nodes = [];
let after = null;
do {
  const res = await fetch('https://api.github.com/graphql', {
    method: 'POST',
    headers: { Authorization: `bearer ${token}`, 'Content-Type': 'application/json', 'User-Agent': 'portfolio-pr-refresh' },
    body: JSON.stringify({ query, variables: { q, after } }),
  });
  const body = await res.json();
  if (!res.ok || body.errors) { console.error(JSON.stringify(body.errors || body)); process.exit(1); }
  nodes.push(...body.data.search.nodes);
  after = body.data.search.pageInfo.hasNextPage ? body.data.search.pageInfo.endCursor : null;
} while (after);

// Titles follow [TYPE][Symbol][Description]; anything else keeps its whole title.
const prs = nodes
  .filter(n => n && n.mergedAt && REPOS[n.repository.nameWithOwner])
  .map(n => {
    const m = n.title.match(/^\[(\w+)\]\[([^\]]*)\]\[(.*)\]$/);
    return {
      kind: REPOS[n.repository.nameWithOwner],
      n: n.number, d: n.mergedAt.slice(0, 10), a: n.additions, r: n.deletions,
      type: m ? m[1].toUpperCase() : 'PR', sym: m ? m[2] : '', desc: m ? m[3] : n.title,
      url: n.url,
    };
  })
  .sort((x, y) => (y.d.localeCompare(x.d)) || (y.n - x.n));

// Merged PRs never go away, so a shorter list means the search came back partial.
const outPath = new URL('../data/prs.js', import.meta.url);
const saved = existsSync(outPath) ? readFileSync(outPath, 'utf8').match(/window\.PRS = (\[.*\]);/s) : null;
const before = saved ? JSON.parse(saved[1]).length : 0;
if (!prs.length || prs.length < before) {
  console.error(`Search returned ${prs.length} PRs but data/prs.js has ${before}. Leaving the file alone.`);
  process.exit(1);
}
const out = `// Generated by scripts/fetch-prs.mjs. Do not edit by hand.\nwindow.PRS = ${JSON.stringify(prs)};\n`;
writeFileSync(outPath, out);
const code = prs.filter(p => p.kind === 'code').length;
console.log(`wrote ${prs.length} PRs (${code} code, ${prs.length - code} docs)`);
